import { describe, expect, it } from 'vitest'
import { remindNewTimed } from '../src/ai-remind'

describe('AI 建的带钟点的待办默认 🔔 准时（remindNewTimed）', () => {
  it('新多出来的带钟点、没 🔔 的补「🔔 准时」；写了提前 1 小时的照写的；没钟点的、勾掉的不补', () => {
    const before = '# 待办\n\n- [ ] 原来的 📅 2026-11-25 10:00\n'
    const after = [
      '# 待办',
      '',
      '- [ ] 原来的 📅 2026-11-25 11:00',
      '- [ ] 交报告 📅 2026-11-25 08:00',
      '- [ ] 开组会 📅 2026-11-25 14:00 🔔 提前1小时',
      '- [ ] 买菜 📅 2026-11-25',
      '- [x] 做完了 📅 2026-11-25 09:00 ✅ 2026-11-25',
      '- [ ] 交周报 📅 2026-11-26 17:00 🆔 a1b2c3',
      '',
    ].join('\n')
    const r = remindNewTimed(before, after)
    expect(r.n).toBe(2)
    expect(r.text.split('\n')).toEqual([
      '# 待办',
      '',
      '- [ ] 原来的 📅 2026-11-25 11:00',
      '- [ ] 交报告 📅 2026-11-25 08:00 🔔 准时',
      '- [ ] 开组会 📅 2026-11-25 14:00 🔔 提前1小时',
      '- [ ] 买菜 📅 2026-11-25',
      '- [x] 做完了 📅 2026-11-25 09:00 ✅ 2026-11-25',
      '- [ ] 交周报 📅 2026-11-26 17:00 🔔 准时 🆔 a1b2c3',
      '',
    ])
  })
  it('新建的一整篇（开始时是空的）也补；没有要补的原样交回', () => {
    expect(remindNewTimed('', '- [ ] 交报告 📅 2026-11-25 08:00').text).toBe('- [ ] 交报告 📅 2026-11-25 08:00 🔔 准时')
    const same = '正文\n\n- [ ] 买菜 📅 2026-11-25\n'
    expect(remindNewTimed('', same)).toEqual({ text: same, n: 0 })
  })
})
