const on =
  <A extends unknown[]>(channel: string) =>
  (cb: (...a: A) => void) => {
    const h = (_e: unknown, ...a: A) => cb(...a)
    ipcRenderer.on(channel, h)
    return () => void ipcRenderer.removeListener(channel, h)
  }

