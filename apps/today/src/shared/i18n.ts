export const TABLES = { zh, en }
export type Key = keyof typeof zh

export type Args<K extends Key> = (typeof zh)[K] extends (...a: infer A) => string ? A : []

/** 取一句：带参数的传参数 */
export function tr<K extends Key>(lang: Lang, key: K, ...args: Args<K>): string {
  const v = (TABLES[lang] as Record<Key, Str | string[]>)[key]
  if (typeof v === 'function') return (v as (...a: unknown[]) => string)(...args)
  return v as string
}

